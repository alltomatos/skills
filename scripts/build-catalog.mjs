#!/usr/bin/env node

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, posix } from 'node:path';

const ROOT = process.cwd();
const MANIFEST = join(ROOT, '.claude-plugin', 'plugin.json');
const REPO = 'alltomatos/skills';
const BRANCH = 'main';
const RAW = `https://raw.githubusercontent.com/${REPO}/${BRANCH}`;
const BLOB = `https://github.com/${REPO}/blob/${BRANCH}`;
const BUCKETS = ['engineering', 'productivity', 'misc'];

function readManifest() {
  const data = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  if (!Array.isArray(data.skills) || data.skills.length === 0) {
    throw new Error('plugin.json sem "skills": nada a catalogar.');
  }
  return data;
}

function frontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const lines = match[1].split(/\r?\n/);
  const fields = {};
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    const key = kv[1];
    let value = kv[2].trim();
    if (/^[>|][-+]?$/.test(value)) {
      const block = [];
      let j = i + 1;
      while (j < lines.length && /^\s+\S/.test(lines[j])) {
        block.push(lines[j].trim());
        j += 1;
      }
      i = j - 1;
      value = block.join(' ');
    } else {
      value = value.replace(/^['"]|['"]$/g, '');
    }
    fields[key] = value.replace(/\s+/g, ' ').trim();
  }
  return fields;
}

function supportFiles(dir) {
  const out = [];
  const walk = (current) => {
    for (const entry of readdirSync(current).sort()) {
      if (entry === 'agents') continue;
      const full = join(current, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry !== 'SKILL.md') out.push(posix.join(...relative(dir, full).split('\\')));
    }
  };
  walk(dir);
  return out;
}

function collect(manifest) {
  return manifest.skills.map((entry) => {
    const relativePath = entry.replace(/^\.\//, '').replace(/\/$/, '');
    const dir = join(ROOT, ...relativePath.split('/'));
    const fields = frontmatter(readFileSync(join(dir, 'SKILL.md'), 'utf8'));
    const name = fields.name || relativePath.split('/').pop();
    const description = fields.description || '';
    const bucket = relativePath.split('/')[1];
    return {
      name,
      bucket,
      description,
      path: `${relativePath}/SKILL.md`,
      dir: relativePath,
      raw: `${RAW}/${relativePath}/SKILL.md`,
      support: supportFiles(dir),
      implicit: fields['disable-model-invocation'] !== 'true',
    };
  });
}

function buildCatalog(skills) {
  const byBucket = BUCKETS
    .map((bucket) => [bucket, skills.filter((s) => s.bucket === bucket)])
    .filter(([, list]) => list.length > 0);

  const lines = [
    '<!-- Generated by scripts/build-catalog.mjs from .claude-plugin/plugin.json. Do not edit by hand. -->',
    '',
    '# Skill catalog',
    '',
    `Single source: \`.claude-plugin/plugin.json\` + each \`SKILL.md\` frontmatter. ${skills.length} skills distributed across ${byBucket.length} buckets.`,
    '',
    '## How to load',
    '',
    '1. A skill is referenced by name in backticks, without a slash: `tdd`, `architect`, `qa-analyst`. To run it, load its `SKILL.md`.',
    '2. Pick the skill by its `when` field and its `path` below.',
    '3. Fetch the `raw` URL or clone the repository and follow the `SKILL.md`.',
    '4. The files listed under `support` sit beside the skill and are needed for it to work.',
    '5. Skills under `skills/personal/` are not distributed and do not appear here.',
    '',
  ];

  for (const [bucket, list] of byBucket) {
    lines.push(`## ${bucket}`, '');
    for (const skill of list) {
      lines.push(`### ${skill.name}`, '');
      lines.push(`- when: ${skill.description}`);
      lines.push(`- path: \`${skill.path}\``);
      lines.push(`- raw: ${skill.raw}`);
      if (skill.support.length > 0) {
        lines.push(`- support: ${skill.support.map((f) => `\`${skill.dir}/${f}\``).join(', ')}`);
      }
      if (!skill.implicit) {
        lines.push('- invocation: explicit only');
      }
      lines.push('');
    }
  }

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

function short(text, max = 150) {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (clean.length <= max) return clean;
  return `${clean.slice(0, max - 1).replace(/[,;.\s]+\S*$/, '')}...`;
}

function buildLlms(skills) {
  const lines = [
    '# alltomatos/skills',
    '',
    '> Skills de engenharia, produtividade e utilitarios para agentes de codigo, com governanca por GitHub Issues e portoes obrigatorios de QA e seguranca.',
    '> Each skill is a directory with a SKILL.md and its support files beside it. The full index, with paths and URLs, lives in SKILLS.md.',
    '',
    '## Skills',
    '',
  ];
  for (const skill of skills) {
    lines.push(`- [${skill.name}](${skill.raw}): ${short(skill.description)}`);
  }
  lines.push('', '## Optional', '');
  lines.push(`- [Full catalog with support files](${RAW}/SKILLS.md): index generated from plugin.json`);
  lines.push(`- [Repository governance](${BLOB}/AGENTS.md): buckets, harness neutrality and the developer contract`);
  lines.push(`- [Engineering flow](${BLOB}/README.md): architecture, governance and the delegation table`);
  return `${lines.join('\n')}\n`;
}

const manifest = readManifest();
const skills = collect(manifest);
writeFileSync(join(ROOT, 'SKILLS.md'), buildCatalog(skills), 'utf8');
writeFileSync(join(ROOT, 'llms.txt'), buildLlms(skills), 'utf8');
console.log(`SKILLS.md and llms.txt generated with ${skills.length} skills.`);
